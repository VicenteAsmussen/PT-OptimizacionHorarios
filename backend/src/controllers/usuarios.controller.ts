import type { Request, Response, NextFunction } from "express";
import { usuariosService } from "../services/usuarios.service.js";

export const usuariosController = {
  async getAll(_req: Request, res: Response, next: NextFunction): Promise<void> {
    try {
      const data = await usuariosService.getAllUsuarios();
      res.status(200).json({
        status: "success",
        data,
      });
    } catch (error) {
      next(error);
    }
  },

  async getById(req: Request, res: Response, next: NextFunction): Promise<void> {
    try {
      const id = Number(req.params.id);
      const data = await usuariosService.getUsuarioById(id);
      res.status(200).json({
        status: "success",
        data,
      });
    } catch (error) {
      next(error);
    }
  },

  async create(req: Request, res: Response, next: NextFunction): Promise<void> {
    try {
      const data = await usuariosService.createUsuario(req.body);
      res.status(201).json({
        status: "success",
        data,
      });
    } catch (error) {
      next(error);
    }
  },

  async update(req: Request, res: Response, next: NextFunction): Promise<void> {
    try {
      const id = Number(req.params.id);
      const data = await usuariosService.updateUsuario(id, req.body);
      res.status(200).json({
        status: "success",
        data,
      });
    } catch (error) {
      next(error);
    }
  },

  async delete(req: Request, res: Response, next: NextFunction): Promise<void> {
    try {
      const id = Number(req.params.id);
      await usuariosService.deleteUsuario(id);
      res.status(204).send();
    } catch (error) {
      next(error);
    }
  },
};
